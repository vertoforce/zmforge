def _cut(text: str, n: int) -> str:
    text = " ".join(str(text).split())
    return text if len(text) <= n else text[: n - 1] + "…"


def visual_line(result: Mapping) -> str | None:
    """One line on whether the rooms were judged from renders (None: not recorded)."""
    visual = result.get("visual")
    if not visual:
        return None
    status = visual.get("status")
    if status == "ok":
        line = (f"visual check: ok, {len(visual.get('rendered') or [])} rooms rendered, "
                f"{len(visual.get('reused') or [])} reused ({visual.get('out')})")
        if visual.get("no_images"):
            line += "; NO renders for " + ", ".join(visual["no_images"])
        return line
    if status == "failed":
        return (f"visual check: FAILED, rooms reviewed without renders, P15 not judged "
                f"from pictures ({_cut(visual.get('error', ''), 200)})")
    return "visual check: skipped (--no-visual), P15 not judged from pictures"


def markdown_report(result: Mapping) -> str:
    facts = result["facts"]
    lines = [f"# Design review: {facts['map']}", ""]
    vline = visual_line(result)
    if vline:
        lines += [f"_{vline[0].upper()}{vline[1:]}._", ""]
    mr = result.get("map_review")
    if mr:
        lines += [f"**Map grade {mr['grade']} ({mr['score']}/10).** {mr['summary']}", ""]
        lines += ["| Principle | Verdict | Evidence | Suggested fix |", "|---|---|---|---|"]
        for p in mr["principles"]:
            lines.append(f"| {p['id']} {p['name']} | {p['verdict']} | {_cut(p['evidence'], 220)} "
                         f"| {_cut(p['suggested_fix'], 220)} |")
        lines.append("")
    else:
        lines += ["**The map-level call failed; see errors.**", ""]
    lines += ["## Rooms", "", "| Room | Grade | Summary | Fails | Warns |", "|---|---|---|---|---|"]
    for r in result.get("room_reviews", []):
        if r.get("error"):
            lines.append(f"| {r['room']} | error | {_cut(r['error'], 120)} | | |")
            continue
        fails = ", ".join(p["id"] for p in r["principles"] if p["verdict"] == "fail")
        warns = ", ".join(p["id"] for p in r["principles"] if p["verdict"] == "warn")
        lines.append(f"| {r['room']} | {r['grade']} ({r['score']}) | {_cut(r['summary'], 200)} "
                     f"| {fails} | {warns} |")
    lines.append("")
    anchored = [r for r in result.get("room_reviews", []) if r.get("anchor")]
    if anchored:
        count = lambda s: sum(1 for r in anchored for f in r["anchor"]["previous_findings"]  # noqa: E731
                              if f["status"] == s)
        changes = sum(len(r["anchor"]["verdict_changes"]) for r in anchored)
        held = sum(len(r["anchor"]["reverted"]) for r in anchored)
        lines += [f"Anchored on the previous review in {len(anchored)} room(s): old findings "
                  f"{count('still_present')} still present, {count('fixed')} fixed, "
                  f"{count('cannot_tell')} cannot tell; {changes} verdict change(s) with a "
                  f"reason, {held} unexplained flip(s) held at the old verdict.", ""]
    sense = (mr or {}).get("doesnt_make_sense", []) + [
        dict(f, where=f"{r['room']}: {f['where']}") for r in result.get("room_reviews", [])
        for f in r.get("doesnt_make_sense", []) if f["severity"] == "high"]
    if sense:
        lines += ["## Doesn't make sense", ""]
        for f in sense:
            lines.append(f"- **{f['severity']}** {f['finding']} ({f['where']}). Fix: {f['suggested_fix']}")
        lines.append("")
    looked = [r for r in result.get("room_reviews", []) if "visual_findings" in r]
    if looked:
        lines += ["## Visual findings", ""]
        for r in looked:
            lines += [f"### {r['room']}", ""]
            if not r["visual_findings"]:
                lines += [f"- none seen in {len(r.get('images') or [])} views", ""]
                continue
            for f in r["visual_findings"]:
                lines.append(f"- **{f['severity']}** {f['what']} ({f['where']}; view `{f['view']}`)")
            lines.append("")
    lines += ["<details><summary>Per-room fails and fixes</summary>", ""]
    for r in result.get("room_reviews", []):
        bad = [p for p in r.get("principles", []) if p["verdict"] in ("fail", "warn")]
        if not bad and not r.get("fixes"):
            continue
        lines.append(f"**{r['room']}**")
        for p in bad:
            lines.append(f"- {p['id']} {p['verdict']}: {_cut(p['evidence'], 240)} Fix: {_cut(p['suggested_fix'], 240)}")
        for fx in r.get("fixes", [])[:8]:
            lines.append(f"- fix [{fx['priority']}] `{fx['target']}`: {_cut(fx['change'], 200)}")
        lines.append("")
    lines += ["</details>", "", "<details><summary>Measured scorecard</summary>", "",
              "```", result.get("scorecard_table", ""), "```", "", "</details>", ""]
    if result.get("errors"):
        lines += ["## Errors", ""] + [f"- {e}" for e in result["errors"]] + [""]
    return "\n".join(lines)


def screen_summary(result: Mapping, paths: Mapping[str, Path] | None = None) -> str:
    facts = result["facts"]
    mr = result.get("map_review")
    lines = [f"== review {facts['map']}"]
    vline = visual_line(result)
    if vline:
        lines.append(vline)
    if mr:
        lines.append(f"map grade {mr['grade']} ({mr['score']}/10): {_cut(mr['summary'], 300)}")
        for p in mr["principles"]:
            if p["verdict"] != "pass":
                lines.append(f"  {p['verdict'].upper():4s} {p['id']} {p['name']}: "
                             f"{_cut(p['suggested_fix'] or p['evidence'], 150)}")
    rooms = [f"{r['room']} {r.get('grade', 'err')}" for r in result.get("room_reviews", [])]
    if rooms:
        lines.append("rooms: " + ", ".join(rooms))
    c = count_verdicts(result)
    lines.append(f"verdicts: {c.get('fail', 0)} fail, {c.get('warn', 0)} warn, {c.get('pass', 0)} pass")
    for e in result.get("errors", []):
        lines.append(f"  ERROR {_cut(e, 160)}")
    for label, path in (paths or {}).items():
        lines.append(f"{label}: {path}")
    return "\n".join(lines)


def write_outputs(result: Mapping, out_dir: Path, stem: str) -> dict[str, Path]:
    out_dir.mkdir(parents=True, exist_ok=True)
    json_path = out_dir / f"{stem}.json"
    md_path = out_dir / f"{stem}.md"
    json_path.write_text(json.dumps(result, indent=1, default=str), encoding="utf-8")
    md_path.write_text(markdown_report(result), encoding="utf-8")
    return {"json": json_path, "report": md_path}
