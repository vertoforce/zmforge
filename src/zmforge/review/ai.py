"""The judgement half of the design review: prompts, anchoring, grading, reports.

Nothing here calls a model.  :mod:`zmforge.review.packet` writes the prompts
this module builds into a review packet; whoever reviews it (a person or any AI agent,
see ``docs/workflows/review-a-map.md``) writes findings in the schema of
:mod:`zmforge.review.schema`; ``zmforge review --import`` then runs the
findings through :func:`normalise` and :func:`apply_anchor` and writes the
report with :func:`write_outputs`.
"""

