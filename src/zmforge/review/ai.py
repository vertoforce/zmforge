PRINCIPLES_PATH = REPO / "docs" / "map-principles.md"
DEFAULT_OUT = REPO / "build-out" / "review"

#: The reviewer's standing instructions: the system prompt of a scripted
#: runner, the first thing an agent reads in a packet's README.
REVIEWER_ROLE = (
    "You are a strict level-design reviewer for Call of Duty: Black Ops III custom "
    "zombies maps generated by a Python tool (zmforge). You judge the facts and "
    "source you are given against the principles, cite concrete evidence (prop ids, "
    "numbers, strings, file:line), and suggest specific fixes a developer can apply "
    "in the recipe code. Do not invent facts that are not in the input. Answer only "
    "with the JSON the schema asks for."
)
SYSTEM = REVIEWER_ROLE  # the old name


class ReviewError(RuntimeError):
    """A findings file (or a runner's answer) is not a review."""


# ----------------------------------------------------------------------
# Principles
# ----------------------------------------------------------------------

_PRINCIPLE = re.compile(r"^- \*\*(P\d+)\s+([^*]+?)\.?\*\*\s*(.*)$")


def load_principles(path: Path = PRINCIPLES_PATH) -> list[dict]:
    """``[{id, name, text}]`` from the principles file, in order."""
    out = []
    for line in Path(path).read_text(encoding="utf-8").splitlines():
        match = _PRINCIPLE.match(line.strip())
        if match:
            out.append({"id": match.group(1), "name": match.group(2).strip(),
                        "text": match.group(3).strip()})
    if not out:
        raise ReviewError(f"no principles found in {path}")
    return out


def principles_text(principles: Sequence[Mapping]) -> str:
    return "\n".join(f"{p['id']} {p['name']}: {p['text']}" for p in principles)


