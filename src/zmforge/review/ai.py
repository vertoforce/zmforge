def extract_json(text: str) -> dict:
    """The JSON object in *text*: bare, in a ```json fence, or between the outer braces."""
    text = text.strip()
    fence = re.search(r"```(?:json)?\s*(\{.*\})\s*```", text, re.DOTALL)
    if fence:
        text = fence.group(1)
    try:
        value = json.loads(text)
    except json.JSONDecodeError:
        start, end = text.find("{"), text.rfind("}")
        if start < 0 or end <= start:
            raise ReviewError(f"no JSON object in the model's answer: {text[:200]!r}")
        try:
            value = json.loads(text[start:end + 1])
        except json.JSONDecodeError as exc:
            raise ReviewError(f"the model's JSON does not parse: {exc}") from exc
    if not isinstance(value, dict):
        raise ReviewError("the model's answer is not a JSON object")
    return value



# ----------------------------------------------------------------------
# Normalising what came back
# ----------------------------------------------------------------------
def _norm_verdict(value: Any, allowed: Sequence[str]) -> tuple[str, str | None]:
    v = str(value or "").strip().lower()
    v = {"passed": "pass", "ok": "pass", "warning": "warn", "failed": "fail",
         "na": "n/a", "not applicable": "n/a"}.get(v, v)
    if v in allowed:
        return v, None
    return "warn", f"reviewer gave an unknown verdict {value!r}; counted as warn"


def _norm_grade(value: Any, score: Any) -> str:
    g = str(value or "").strip().upper()[:1]
    if g in GRADES:
        return g
    if g == "E":
        return "F"
    try:
        s = float(score)
    except (TypeError, ValueError):
        return "F"
    return "A" if s >= 9 else "B" if s >= 7.5 else "C" if s >= 6 else "D" if s >= 4.5 else "F"


def _norm_score(value: Any) -> float | None:
    try:
        return max(0.0, min(10.0, float(value)))
    except (TypeError, ValueError):
        return None


def _norm_findings(items: Any) -> list[dict]:
    out = []
    for item in items if isinstance(items, list) else []:
        if not isinstance(item, Mapping):
            item = {"finding": str(item)}
        severity = str(item.get("severity", "medium")).lower()
        out.append({
            "finding": str(item.get("finding") or item.get("what") or ""),
            "severity": severity if severity in SEVERITIES else "medium",
            "where": str(item.get("where", "")),
            "suggested_fix": str(item.get("suggested_fix") or item.get("fix") or ""),
        })
    return out


def _norm_fixes(items: Any) -> list[dict]:
    out = []
    for item in items if isinstance(items, list) else []:
        if not isinstance(item, Mapping):
            item = {"change": str(item)}
        priority = str(item.get("priority", "medium")).lower()
        out.append({"target": str(item.get("target", "")), "change": str(item.get("change", "")),
                    "priority": priority if priority in SEVERITIES else "medium"})
    return out


def _norm_visual_findings(items: Any) -> list[dict]:
    out = []
    for item in items if isinstance(items, list) else []:
        if not isinstance(item, Mapping):
            item = {"what": str(item)}
        severity = str(item.get("severity", "medium")).lower()
        out.append({
            "what": str(item.get("what") or item.get("finding") or ""),
            "where": str(item.get("where", "")),
            # The file name only: the model sometimes echoes a path.
            "view": Path(str(item.get("view") or item.get("image") or "")).name,
            "severity": severity if severity in SEVERITIES else "medium",
        })
    return out


def _apply_visual_findings(principles_out: list[dict], findings: Sequence[Mapping],
                           notes: list[str]) -> None:
    """Visual findings count against P15: a room with any cannot pass it.

    The floor is ``warn`` (the level the verdicts use for "fix this, the map
    still works"), raised to ``fail`` when a finding is ``high`` severity (a
    player would notice at once), because ``fail`` is what ``--strict``
    blocks on.  A worse verdict the model already gave is kept.  ``n/a`` is
    lifted too: with pictures attached, P15 can always be judged.
    """
    if not findings:
        return
    floor = "fail" if any(f["severity"] == "high" for f in findings) else "warn"
    rank = {"n/a": 0, "pass": 1, "warn": 2, "fail": 3}
    for p in principles_out:
        if p["id"] != VISUAL_PRINCIPLE or rank.get(p["verdict"], 2) >= rank[floor]:
            continue
        notes.append(f"{VISUAL_PRINCIPLE}: {p['verdict']} raised to {floor} by "
                     f"{len(findings)} visual finding(s)")
        p["evidence"] = (f"{len(findings)} visual finding(s) in the renders. "
                         + p["evidence"]).strip()
        p["verdict"] = floor


def normalise(raw: Mapping, principles: Sequence[Mapping], *, allow_na: bool,
              visual: bool = False) -> dict:
    """A review with one entry per principle, in the file's order, and nothing odd.

    A principle the model skipped is recorded as ``warn`` with a note, not
    dropped: a silent gap reads as a pass.  Extra ids are kept at the end.
    With *visual* (renders were attached) the answer's ``visual_findings`` are
    kept and count against P15; without, no ``visual_findings`` key is written.
    """
    allowed = ROOM_VERDICTS if allow_na else VERDICTS
    given: dict[str, Mapping] = {}
    for item in raw.get("principles") or []:
        if isinstance(item, Mapping) and item.get("id"):
            given[str(item["id"]).strip().upper().split()[0]] = item
    notes = []
    principles_out = []
    known = [p["id"] for p in principles]
    for p in principles:
        item = given.get(p["id"])
        if item is None:
            principles_out.append({"id": p["id"], "name": p["name"], "verdict": "warn",
                                   "evidence": "not assessed by the reviewer",
                                   "suggested_fix": ""})
            notes.append(f"{p['id']} missing from the answer")
            continue
        verdict, note = _norm_verdict(item.get("verdict"), allowed)
        if note:
            notes.append(f"{p['id']}: {note}")
        principles_out.append({"id": p["id"], "name": p["name"], "verdict": verdict,
                               "evidence": str(item.get("evidence", "")),
                               "suggested_fix": str(item.get("suggested_fix")
                                                    or item.get("fix") or "")})
    for pid, item in given.items():
        if pid not in known:
            notes.append(f"unknown principle id {pid} ignored")
    score = _norm_score(raw.get("score"))
    out = {
        "grade": _norm_grade(raw.get("grade"), score),
        "score": score,
        "summary": str(raw.get("summary", "")),
        "principles": principles_out,
        "fixes": _norm_fixes(raw.get("fixes")),
        "doesnt_make_sense": _norm_findings(raw.get("doesnt_make_sense")
                                            or raw.get("findings")),
    }
    if visual:
        out["visual_findings"] = _norm_visual_findings(raw.get("visual_findings"))
        _apply_visual_findings(principles_out, out["visual_findings"], notes)
    if "room" in raw:
        out["room"] = str(raw["room"])
    if notes:
        out["normalise_notes"] = notes
    return out


def count_verdicts(result: Mapping) -> dict[str, int]:
    counts = {v: 0 for v in ROOM_VERDICTS}
    reviews = [result.get("map_review")] + list(result.get("room_reviews") or [])
    for review in reviews:
        for p in (review or {}).get("principles", []):
            counts[p["verdict"]] = counts.get(p["verdict"], 0) + 1
    return counts


def exit_code(result: Mapping, *, strict: bool) -> int:
    """0 unless *strict* and any principle failed (map or room) or a call failed."""
    if not strict:
        return 0
    if result.get("errors"):
        return 1
    return 1 if count_verdicts(result).get("fail", 0) else 0


