VISUAL_NOTE = """
RENDERED VIEWS (attached images, in order: {names})
These are Radiant 3D-camera shots of this room with the real stock models and materials: high views from two corners, then eye height (60 units) from each doorway. Custom materials never registered in the local asset database draw solid black; judge their placement, not their look. Editor lights may show as yellow bulb icons; ignore them.
Judge P15 from these pictures first. Go through the room cluster by cluster (a counter and what is on it, a row of posts, a desk group, a shelf unit) and for each one that does not make sense to a person say: what it is, why it seems to be here, and what is missing or absurd (an assembly with parts missing, such as stanchion posts with no belts between them or a desk with no chair; things floating, sunk, facing a wall or inside each other; a bare wall or floor where the room's purpose needs something; wrong scale; clutter that is only there to raise a count). Put each one in visual_findings: what (the problem and why it looks wrong), where (the spot in the room, naming the prop ids from the facts where you can match them), view (the file name of the image you saw it in, from the list above) and severity. Give P15 its verdict from what you see: any visual finding means P15 is not a pass. Keep doesnt_make_sense for problems found in the facts and source.
"""


def room_prompt(principles: Sequence[Mapping], room: Mapping, source: str, *,
                map_name: str, thresholds: Mapping, images: Sequence[str] = (),
                previous: Mapping | None = None) -> str:
    visual = VISUAL_NOTE.format(names=", ".join(images)) if images else ""
    visual += anchor_text(previous) if previous else ""
    return f"""Review ONE room of the zombies map {map_name}.

PRINCIPLES (judge each; use "n/a" only for a principle that cannot be judged from one room, such as P6 quest variety, P7 essentials or P8 progression -- but do judge the parts of them that live in this room):
{principles_text(principles)}

HOW TO READ THE FACTS
- Units are game units (about an inch). Positions ("rel") are [x, y, z] from the room's south-west floor corner; x east, y north.
- props rows follow props_columns. wall_gap = distance from the footprint edge to the nearest wall face (negative = into the wall); door_gap = distance to the nearest opening; sits_on = the highest thing under the prop's centre ("floor", "prop <id>", "fixture <id>", "wall-mounted").
- fixtures are solid brush geometry (counters, shelves, walls of the maze).
- scorecard thresholds: {json.dumps(thresholds)}. The scorecard is measured by code and is reliable; your job is the judgement the numbers cannot make (does the layout read as a real room, are groupings sensible, is the theme strong, do the strings make sense here).
- The source is the recipe code that dresses this room; use it to check intent against result (e.g. a gag wired to the wrong room, a string that names something absent) and cite file:line.

Grade the room A-F and 0-10. List concrete fixes naming prop ids / element ids / file:line. List anything that does not make sense to a player under doesnt_make_sense.

ROOM FACTS (JSON):
{json.dumps(room, separators=(",", ":"), default=str)}

RECIPE SOURCE FOR THIS ROOM:
{source or "(none found)"}
{visual}"""


#: What the map prompt says in place of the room grades when it is written
#: before the rooms are graded (a review packet): the reviewer adds their own.
ROOM_REVIEWS_LATER = (
    "(not in this file: grade every room call of this packet first, then weigh your own "
    "room findings here -- each room's grade, score, summary and failed principles, as "
    "room_digest in zmforge.review.ai lists them)")


def room_digest(room_reviews: Sequence[Mapping]) -> list[dict]:
    """What the map call sees of each room review: grade, score, summary, fails."""
    return [{"room": r.get("room"), "grade": r.get("grade"), "score": r.get("score"),
             "summary": r.get("summary"),
             "fails": [p.get("id") for p in r.get("principles") or ()
                       if isinstance(p, Mapping) and p.get("verdict") == "fail"]}
            for r in room_reviews]


def map_prompt(principles: Sequence[Mapping], facts: Mapping,
               room_reviews: Sequence[Mapping] | None, source: str) -> str:
    """The map call's prompt; *room_reviews* None leaves the grades to the reviewer."""
    rooms = [{"room": r["room"], "size": r["size"], "materials": r["materials"],
              "scorecard": r["scorecard"], "notices": len(r["notices"]),
              "interactives": [i.get("kind") + ":" + str(i.get("what") or i.get("id"))
                               for i in r["interactives"]]}
             for r in facts["rooms"]]
    grades = (ROOM_REVIEWS_LATER if room_reviews is None
              else json.dumps(room_digest(room_reviews), separators=(",", ":"), default=str))
    whole = {k: v for k, v in facts.items() if k not in ("rooms",)}
    return f"""Review the WHOLE zombies map {facts['map']} (recipe {facts['recipe']}).

PRINCIPLES (give every one a verdict pass, warn or fail):
{principles_text(principles)}

Per-room reviews have already been done (grades below); weigh them for P1-P5 but judge the map as a whole: essentials, progression (door graph with cheapest cost into each zone), the quest and boss, the ending, every on-screen string, and the check results. Read the source to find things that cannot work or do not make sense (a step that can never trigger, a string that refers to something absent, a hint that points to the wrong room). Positions are world units; quest_points give each quest point's room and whether spawn-reached floor is under it.

WHERE THE EVIDENCE IS
- P2: each room's scorecard `counted_props` against its `density_floor` (`counted_props` is `props` with floor litter capped: litter past a quarter of the counted props does not count, and `litter_share` above ~0.25 means the room is padded with litter) (a floor, never an upper band: do not mark a room down for carrying more), and MAP FACTS `engine_limits` (the only upper bounds: props and shadowing lamps against their ceilings). A room's `foliage_evenness` is the Clark-Evans ratio of its plants (about 1 is an even scatter, under 0.75 clumped): plants should gather at wall feet, grave edges, kerbs and tree bases with bare ground between (Z66).
- P12 and P13: MAP FACTS `script.threads` lists every function of the generated server script that loops, or waits and then shows a line: its `endon` events, exits inside the loop, what threads it, what it notifies, its waits, whether its timing is random, and `lines_shown` as [call, string ref, text]. `script.source` has the code of those that show lines or loop forever with no endon. A loop that belongs to a quest step and does not end on that step's done or end event fails P12; a line shown on a timer or at random that carries no information, or that can land on top of a live timed cue, fails P13.
- P14: `essentials` pair each perk machine's `name` with the `model` it shows; quest objects carry their own `model` in the quest facts, and each quest point lists its `nearest_props` [id, model, distance] for steps that aim at a prop the map already places.

Grade the map A-F and 0-10, with concrete fixes (file:line or element id) and a list of anything that does not make sense to a player.

ROOM SCORECARDS (JSON):
{json.dumps(rooms, separators=(",", ":"), default=str)}

ROOM REVIEWS (JSON):
{grades}

MAP FACTS (JSON):
{json.dumps(whole, separators=(",", ":"), default=str)}

QUEST / GAG / STRING SOURCE:
{source or "(none found)"}
"""


# ----------------------------------------------------------------------
# Anchoring a room review on the previous one
# ----------------------------------------------------------------------
#: How many earlier review files to search for a room's last good review.
ANCHOR_FILES = 20
#: How much of a previous verdict's evidence goes back into the prompt.
ANCHOR_EVIDENCE = 300


def _review_files(out_dir: Path, map_name: str) -> list[Path]:
    """This map's full review JSONs (not ``--no-ai`` facts), newest first."""
    pattern = re.compile(rf"^{re.escape(map_name)}-\d{{8}}-\d{{6}}\.json$")
    return sorted((p for p in Path(out_dir).glob(f"{map_name}-*.json")
                   if pattern.match(p.name)), key=lambda p: p.name, reverse=True)


def _changed_keys(before: Mapping | None, now: Mapping | None) -> list[str] | None:
    if before is None or now is None:
        return None
    keys = sorted(set(before) | set(now))
    dump = lambda v: json.dumps(v, sort_keys=True, default=str)  # noqa: E731
    return [k for k in keys if dump(before.get(k)) != dump(now.get(k))]


def previous_room_reviews(out_dir: Path, map_name: str, facts: Mapping,
                          rooms: Sequence[str] | None = None) -> dict[str, dict]:
    """Room key -> the anchor for that room: its most recent good review.

    Searched per room, newest file first, so a ``--rooms`` run that reviewed
    only two rooms does not hide the others' last review.  A room whose last
    call errored falls back to the one before.  Each anchor carries the
    verdicts, the findings numbered for the model to answer, and which keys
    of the room's facts differ from the facts that review saw.
    """
    now = {r["room"]: r for r in facts.get("rooms", ())}
    wanted = [r for r in (rooms or now) if r in now]
    anchors: dict[str, dict] = {}
    for path in _review_files(out_dir, map_name)[:ANCHOR_FILES]:
        if len(anchors) == len(wanted):
            break
        try:
            old = json.loads(path.read_text(encoding="utf-8"))
        except (OSError, ValueError):
            continue
        old_facts = {r.get("room"): r for r in (old.get("facts") or {}).get("rooms", ())}
        for review in old.get("room_reviews") or ():
            room = review.get("room")
            if room not in wanted or room in anchors or review.get("error") \
                    or not review.get("principles"):
                continue
            findings = [{"kind": "doesnt_make_sense", "text": f.get("finding", ""),
                         "where": f.get("where", ""), "severity": f.get("severity", "")}
                        for f in review.get("doesnt_make_sense") or ()]
            findings += [{"kind": "visual", "text": f.get("what", ""),
                          "where": f.get("where", ""), "severity": f.get("severity", ""),
                          "view": f.get("view", "")}
                         for f in review.get("visual_findings") or ()]
            for n, f in enumerate(findings, 1):
                f["n"] = n
            anchors[room] = {
                "from": path.stem, "grade": review.get("grade"), "score": review.get("score"),
                "principles": [{"id": p["id"], "verdict": p.get("verdict"),
                                "evidence": _cut(str(p.get("evidence", "")), ANCHOR_EVIDENCE)}
                               for p in review["principles"]],
                "findings": findings,
                "facts_changed": _changed_keys(old_facts.get(room), now[room]),
                "had_images": bool(review.get("images")),
            }
    return anchors


def anchor_text(anchor: Mapping) -> str:
    """The prompt block that anchors a room call on its previous review."""
    changed = anchor.get("facts_changed")
    if changed is None:
        changed_line = "unknown (the previous facts were not stored)"
    else:
        changed_line = ", ".join(changed) if changed else "none"
    verdicts = "\n".join(f"- {p['id']}: {p['verdict']} -- {p['evidence']}"
                         for p in anchor.get("principles", ()))
    findings = "\n".join(
        f"{f['n']}. [{f['kind']}, {f.get('severity') or '?'}] {f['text']}"
        + (f" -- where: {f['where']}" if f.get("where") else "")
        + (f" -- view: {f['view']}" if f.get("view") else "")
        for f in anchor.get("findings", ())) or "(none)"
    return f"""
PREVIOUS REVIEW OF THIS ROOM ({anchor['from']}: grade {anchor.get('grade')}, score {anchor.get('score')})
This room was reviewed before. Reviews of an unchanged room have flipped between runs with nothing behind the flip, and the map's builders then chase that noise, so this review is anchored on the previous one.
- Keys of the ROOM FACTS that changed since then: {changed_line}. The recipe source{' and the renders' if anchor.get('had_images') else ''} may have changed too; compare them against each finding.
- For EVERY numbered finding below, put an entry in previous_findings: still_present, fixed or cannot_tell, with the evidence (prop ids, numbers, the view it shows in). A finding that is still present is listed again, in the same words, in doesnt_make_sense or visual_findings; a fixed one is not.
- Keep each principle's previous verdict unless (a) something it rested on changed, or (b) you can name a new concrete defect: a prop id, element id, file:line or view file name, and what is wrong with it. List every verdict that differs from the previous one in verdict_changes with that reason. A changed verdict missing from verdict_changes is set back to the previous verdict.
- A new finding must be concrete in the same sense. A general impression that the previous review did not raise, about a room that did not change, is not a new defect.

PREVIOUS VERDICTS:
{verdicts}

PREVIOUS FINDINGS:
{findings}
"""


def apply_anchor(review: dict, raw: Mapping, anchor: Mapping) -> dict:
    """Hold unexplained verdict flips at the previous verdict; record the anchor.

    A principle whose verdict differs from the anchor's and which the answer
    does not list in ``verdict_changes`` (with a reason) goes back to the
    previous verdict.  P15 with visual findings is left to the visual rule
    (:func:`_apply_visual_findings`): a room with a visual finding cannot pass.
    """
    before = {p["id"]: p.get("verdict") for p in anchor.get("principles", ())}
    listed = {}
    for item in raw.get("verdict_changes") or ():
        if isinstance(item, Mapping) and item.get("id") and str(item.get("reason", "")).strip():
            listed[str(item["id"]).strip().upper().split()[0]] = {
                "id": str(item["id"]).strip().upper().split()[0],
                "previous": str(item.get("previous", "")), "now": str(item.get("now", "")),
                "reason": str(item["reason"])}
    has_visual = bool(review.get("visual_findings"))
    reverted = []
    for p in review["principles"]:
        old = before.get(p["id"])
        if old is None or old == p["verdict"] or p["id"] in listed or old not in ROOM_VERDICTS:
            continue
        if p["id"] == VISUAL_PRINCIPLE and has_visual:
            continue
        reverted.append({"id": p["id"], "previous": old, "answered": p["verdict"]})
        p["evidence"] = (f"(kept {old} from {anchor['from']}: the change to {p['verdict']} "
                         f"gave no reason) " + p["evidence"]).strip()
        p["verdict"] = old
    statuses = []
    for item in raw.get("previous_findings") or ():
        if not isinstance(item, Mapping):
            continue
        status = str(item.get("status", "")).lower()
        statuses.append({"n": item.get("n"),
                         "status": status if status in PREVIOUS_STATUS else "cannot_tell",
                         "note": str(item.get("note", ""))})
    answered = {s["n"] for s in statuses}
    review["anchor"] = {
        "from": anchor["from"],
        "facts_changed": anchor.get("facts_changed"),
        "previous_findings": statuses,
        "unanswered": [f["n"] for f in anchor.get("findings", ()) if f["n"] not in answered],
        "verdict_changes": list(listed.values()),
        "reverted": reverted,
    }
    return review


