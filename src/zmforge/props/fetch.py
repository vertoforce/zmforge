"""Download and unpack the asset kits, once, into a cache outside the repo.

The kits are other people's files.  They are not committed: the repo keeps the
record of *what* was downloaded and under which licence (``library.py``) and
this module fetches it on demand, so a fresh clone can rebuild the props
without a binary ever entering git history.

The cache defaults to ``<repo>/assets-cache`` and is gitignored.  A kit is
downloaded only if its archive is not already there; nothing is re-fetched to
"check for updates", because a kit that silently changed under a built map is
exactly the surprise this pipeline exists to avoid.
"""

from __future__ import annotations

import urllib.request
import zipfile
from pathlib import Path

import json
import urllib.parse

from .library import KITS, TEXTURES, Kit

__all__ = ["default_cache", "archive_path", "ensure_kit", "extract_prop", "extract_texture",
           "kit_cached", "ensure_texture_source", "extract_texture_member"]

_UA = "zmforge/props (asset pipeline)"


def default_cache() -> Path:
    """``<repo root>/assets-cache`` -- gitignored, beside the package."""
    return Path(__file__).resolve().parents[3] / "assets-cache"


def archive_path(kit: Kit, cache: Path) -> Path:
    """The kit's local copy: its ``.zip``, or for a glTF kit its ``.gltf``
    (in a folder of its own, beside the buffers and images it names)."""
    if kit.kind == "gltf":
        return cache / "downloads" / kit.slug / kit.archive.rsplit("/", 1)[-1]
    return cache / "downloads" / kit.archive.rsplit("/", 1)[-1]


def kit_cached(kit: Kit, cache: Path | None = None) -> bool:
    """Whether the kit needs no download (cached, or generated by our code)."""
    if kit.kind == "generated":
        return True
    return archive_path(kit, cache or default_cache()).is_file()


def _download(url: str, timeout: float) -> bytes:
    request = urllib.request.Request(url, headers={"User-Agent": _UA})
    with urllib.request.urlopen(request, timeout=timeout) as response:
        return response.read()


def _ensure_gltf(kit: Kit, target: Path, timeout: float) -> Path:
    """The ``.gltf`` plus every relative ``uri`` it names (buffers, images)."""
    if target.is_file() and target.stat().st_size > 0:
        return target
    target.parent.mkdir(parents=True, exist_ok=True)
    payload = _download(kit.archive, timeout)
    doc = json.loads(payload)
    # Poly Haven serves a model's buffer and images from other folders than
    # its .gltf (the .bin under gltf/8k/, the images
    # under jpg/1k/), so the relative uris do not resolve against it.  Its
    # files API names the real URL of every one.
    where: dict[str, str] = {}
    if urllib.parse.urlparse(kit.archive).netloc == "dl.polyhaven.org":
        asset = kit.archive.rstrip("/").split("/")[-2]
        files = json.loads(_download(f"https://api.polyhaven.com/files/{asset}", timeout))
        for res in files.get("gltf", {}).values():
            gltf = res.get("gltf", {})
            if gltf.get("url") == kit.archive:
                where = {k: v["url"] for k, v in gltf.get("include", {}).items()}
    for item in [*doc.get("buffers", []), *doc.get("images", [])]:
        uri = item.get("uri", "")
        if not uri or uri.startswith("data:"):
            continue
        rel = Path(urllib.parse.unquote(uri))
        if rel.is_absolute() or ".." in rel.parts:
            raise RuntimeError(f"{kit.slug}: refusing uri {uri!r} outside the model folder")
        out = target.parent / rel
        if not out.is_file():
            out.parent.mkdir(parents=True, exist_ok=True)
            url = where.get(rel.as_posix()) or urllib.parse.urljoin(kit.archive, uri)
            out.write_bytes(_download(url, timeout))
    target.write_bytes(payload)  # last, so a half-fetched model is fetched again
    return target


def ensure_kit(slug: str, cache: Path | None = None, *, timeout: float = 180) -> Path:
    """Return the kit's local ``.zip`` (or ``.gltf``), downloading it if not cached."""
    kit = KITS[slug]
    if kit.kind == "generated":
        raise ValueError(f"{slug}: a generated kit has nothing to download")
    cache = cache or default_cache()
    target = archive_path(kit, cache)
    if kit.kind == "gltf":
        return _ensure_gltf(kit, target, timeout)
    if target.is_file() and target.stat().st_size > 0:
        return target
    target.parent.mkdir(parents=True, exist_ok=True)
    payload = _download(kit.archive, timeout)
    if not payload.startswith(b"PK"):
        raise RuntimeError(f"{kit.slug}: {kit.archive} did not return a zip archive")
    target.write_bytes(payload)
    return target


def ensure_texture_source(slug: str, cache: Path | None = None, *,
                          timeout: float = 300) -> Path:
    """Return a :data:`TEXTURES` source's local ``.zip``, downloading it once."""
    tex = TEXTURES[slug]
    cache = cache or default_cache()
    target = cache / "downloads" / f"{tex.slug}.zip"
    if target.is_file() and target.stat().st_size > 0:
        return target
    target.parent.mkdir(parents=True, exist_ok=True)
    payload = _download(tex.archive, timeout)
    if not payload.startswith(b"PK"):
        raise RuntimeError(f"{tex.slug}: {tex.archive} did not return a zip archive")
    target.write_bytes(payload)
    return target


def extract_texture_member(slug: str, member: str, into: Path,
                           cache: Path | None = None) -> Path:
    """Unpack one image of a texture source and return its path."""
    archive = ensure_texture_source(slug, cache)
    into.mkdir(parents=True, exist_ok=True)
    out = into / f"{slug}_{member.rsplit('/', 1)[-1]}"
    with zipfile.ZipFile(archive) as zf:
        if member not in zf.namelist():
            raise KeyError(f"{slug}: {member} is not in {archive.name}")
        out.write_bytes(zf.read(member))
    return out


def extract_prop(slug: str, member: str, into: Path, cache: Path | None = None) -> Path:
    """Unpack ``<member>.obj`` (and its ``.mtl``) and return the ``.obj`` path.

    A glTF kit's model is used where it was fetched: its path is returned.
    """
    kit = KITS[slug]
    if kit.kind == "generated":
        raise ValueError(f"{slug}: generated props have no file (props/build.load_mesh)")
    archive = ensure_kit(slug, cache)
    if kit.kind == "gltf":
        return archive.parent / member
    into.mkdir(parents=True, exist_ok=True)
    obj = into / f"{member}.obj"
    with zipfile.ZipFile(archive) as zf:
        names = set(zf.namelist())
        for suffix in (".obj", ".mtl"):
            inside = f"{kit.obj_dir}/{member}{suffix}"
            if inside not in names:
                if suffix == ".obj":
                    raise KeyError(f"{kit.slug}: {inside} is not in {archive.name}")
                continue
            (into / f"{member}{suffix}").write_bytes(zf.read(inside))
    return obj


def extract_texture(slug: str, into: Path, cache: Path | None = None) -> Path | None:
    """Unpack the kit's shared texture, or return None if it ships none."""
    kit = KITS[slug]
    if kit.texture is None:
        return None
    archive = ensure_kit(slug, cache)
    into.mkdir(parents=True, exist_ok=True)
    out = into / f"{kit.slug}_{kit.texture.rsplit('/', 1)[-1]}"
    with zipfile.ZipFile(archive) as zf:
        out.write_bytes(zf.read(kit.texture))
    return out
